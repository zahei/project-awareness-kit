#!/usr/bin/env python3
"""
pak (Project Awareness Kit) — Zero-Token Polyglot Codebase Atlas & Dependency Graph Generator.
Scans live source files across Go, TypeScript/JavaScript/React, Python, Rust,
SQL, Protobuf, GraphQL/OpenAPI, and CSS/i18n (skipping generated & quarantined
paths configured in `pak.config.json`) plus dynamic `docs/domains/*.md` dossiers
to emit compact indexes and reverse-dependent graphs in `docs/atlas/`.

Runs in <0.5s using Python 3 stdlib only (0 LLM tokens, 0 pip dependencies).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Set, Tuple

ROOT = Path(__file__).resolve().parents[2]
CONFIG_PATH = ROOT / "pak.config.json"
ATLAS_DIR = ROOT / "docs" / "atlas"
DOMAINS_DIR = ROOT / "docs" / "domains"

DEFAULT_IGNORED_DIRS = {
    ".git",
    ".hg",
    ".svn",
    ".agents",
    ".agent",
    ".claude",
    ".codex",
    ".cursor",
    "node_modules",
    "dist",
    "build",
    ".next",
    "out",
    "target",
    "vendor",
    "coverage",
    ".venv",
    "venv",
    "__pycache__",
    "docs",
    "scripts",
}


def load_config() -> Dict[str, Any]:
    if CONFIG_PATH.exists():
        try:
            return json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
        except Exception as exc:
            print(f"[pak:atlas] Warning: failed parsing pak.config.json ({exc}); using defaults", file=sys.stderr)
    return {
        "project_name": ROOT.name,
        "quarantined_paths": [],
        "generated_paths": list(DEFAULT_IGNORED_DIRS),
        "checks": {},
    }


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def is_skipped(rel_path: str, cfg: Dict[str, Any]) -> bool:
    norm = rel_path.replace("\\", "/").lstrip("./")
    parts = norm.split("/")
    if parts[0] in DEFAULT_IGNORED_DIRS:
        return True
    for prefix in cfg.get("quarantined_paths", []) + cfg.get("generated_paths", []):
        p = prefix.strip("/").replace("\\", "/")
        if not p:
            continue
        if norm == p or norm.startswith(p + "/") or f"/{p}/" in f"/{norm}/":
            return True
    return False


def walk_source_files(cfg: Dict[str, Any], suffixes: tuple[str, ...]) -> List[Path]:
    matched: List[Path] = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        d_path = Path(dirpath)
        d_rel = "" if d_path == ROOT else rel(d_path)
        dirnames[:] = sorted(
            d for d in dirnames
            if d not in DEFAULT_IGNORED_DIRS
            and not d.startswith(".")
            and not is_skipped(f"{d_rel}/{d}".lstrip("/"), cfg)
        )
        for fname in sorted(filenames):
            if not fname.endswith(suffixes):
                continue
            full = d_path / fname
            r = rel(full)
            if not is_skipped(r, cfg):
                matched.append(full)
    return matched


def build_code_capabilities(cfg: Dict[str, Any]) -> str:
    out: List[str] = [
        "# Code Capabilities & Symbol Reuse Index",
        "",
        "> Auto-generated by `scripts/pak/build_atlas.py`.",
        "> **Anti-Duplication Rule:** Search this file (or run `bash scripts/pak/blast_radius.sh <term>`) BEFORE writing any new helper, service method, hook, or class.",
        "",
    ]

    go_files = [p for p in walk_source_files(cfg, (".go",)) if not p.name.endswith("_test.go")]
    if go_files:
        out.append("## Go Packages & Exported Symbols")
        go_type_re = re.compile(r"^type\s+([A-Z][A-Za-z0-9_]*)\s+(interface|struct|[A-Za-z0-9_\[\]*\.]+)")
        go_func_re = re.compile(r"^func\s+(?:\([^)]+\)\s+)?([A-Z][A-Za-z0-9_]*)\s*\(")
        go_iface_m_re = re.compile(r"^\t([A-Z][A-Za-z0-9_]*)\((.*)\)\s*(.*)$")
        for p in go_files:
            lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
            items: List[str] = []
            in_iface = ""
            i = 0
            while i < len(lines):
                ln = lines[i]
                if in_iface:
                    if ln.startswith("}"):
                        in_iface = ""
                    else:
                        mm = go_iface_m_re.match(ln)
                        if mm:
                            items.append(f"  - L{i+1}: `{in_iface}.{mm.group(1)}({mm.group(2)}) {mm.group(3).strip()}`")
                    i += 1
                    continue
                mt = go_type_re.match(ln)
                if mt:
                    items.append(f"- L{i+1} `type {mt.group(1)} {mt.group(2)}`")
                    if mt.group(2) == "interface" and "{" in ln and not ln.rstrip().endswith("}"):
                        in_iface = mt.group(1)
                    i += 1
                    continue
                if go_func_re.match(ln):
                    sig = [ln.strip()]
                    j = i
                    while not sig[-1].endswith("{") and j + 1 < len(lines) and (j - i) < 6:
                        j += 1
                        sig.append(lines[j].strip())
                    s = re.sub(r"\s+", " ", " ".join(sig)).rstrip("{").strip()
                    items.append(f"- L{i+1} `{s}`")
                    i = j + 1
                    continue
                i += 1
            if items:
                out.append(f"\n### `{rel(p)}`")
                out.extend(items)
        out.append("")

    ts_files = [
        p for p in walk_source_files(cfg, (".ts", ".tsx", ".js", ".jsx", ".mjs"))
        if not any(seg in p.name for seg in (".test.", ".spec.", ".stories."))
        and not p.name.endswith(".d.ts")
    ]
    if ts_files:
        out.append("## TypeScript / JavaScript Exports")
        ts_exp_re = re.compile(
            r"^export\s+(?:default\s+)?(?:async\s+)?(function|const|class|interface|type|enum)\s+([A-Za-z0-9_]+)"
        )
        for p in ts_files:
            r = rel(p)
            if "/locales/" in r:
                continue
            exports: List[str] = []
            for idx, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                m = ts_exp_re.match(ln.strip())
                if m:
                    exports.append(f"`{m.group(2)}` ({m.group(1)}, L{idx})")
            if exports:
                out.append(f"- `{r}`: " + ", ".join(exports))
        out.append("")

    py_files = [
        p for p in walk_source_files(cfg, (".py",))
        if not p.name.startswith("test_") and not p.name.endswith("_test.py") and p.name != "__init__.py"
    ]
    if py_files:
        out.append("## Python Modules, Classes & Functions")
        py_sym_re = re.compile(r"^(class|def|async\s+def)\s+([A-Za-z][A-Za-z0-9_]*)\s*[\(:]")
        for p in py_files:
            syms: List[str] = []
            for idx, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                m = py_sym_re.match(ln)
                if m and not m.group(2).startswith("_"):
                    kind = "fn" if "def" in m.group(1) else "class"
                    syms.append(f"`{m.group(2)}` ({kind}, L{idx})")
            out.append(f"- `{rel(p)}`: " + (", ".join(syms) if syms else "_(script)_"))
        out.append("")

    rs_files = walk_source_files(cfg, (".rs",))
    if rs_files:
        out.append("## Rust Public Symbols")
        rs_re = re.compile(r"^\s*pub(?:\([^)]+\))?\s+(?:async\s+)?(fn|struct|enum|trait|type|mod)\s+([A-Za-z0-9_]+)")
        for p in rs_files:
            syms = []
            for idx, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                m = rs_re.match(ln)
                if m:
                    syms.append(f"`{m.group(2)}` ({m.group(1)}, L{idx})")
            if syms:
                out.append(f"- `{rel(p)}`: " + ", ".join(syms))
        out.append("")

    if len(out) <= 6:
        out.append("_(No source files indexed yet — add code and run `python3 scripts/pak/build_atlas.py`.)_\n")

    return "\n".join(out).rstrip() + "\n"


def build_data_contracts(cfg: Dict[str, Any]) -> str:
    out: List[str] = [
        "# Data Contracts: APIs, Schemas & Queries",
        "",
        "> Auto-generated by `scripts/pak/build_atlas.py`.",
        "",
    ]

    proto_files = walk_source_files(cfg, (".proto",))
    if proto_files:
        out.append("## Protobuf Services & RPCs")
        svc_re = re.compile(r"^service\s+([A-Za-z0-9_]+)")
        rpc_re = re.compile(r"^\s*rpc\s+([A-Za-z0-9_]+)\s*\(([^)]+)\)\s*returns\s*\(([^)]+)\)")
        msg_re = re.compile(r"^message\s+([A-Za-z0-9_]+)")
        for p in proto_files:
            cur_svc = ""
            rpcs, msgs = [], []
            for idx, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                ms = svc_re.match(ln.strip())
                if ms:
                    cur_svc = ms.group(1)
                    continue
                mr = rpc_re.match(ln)
                if mr:
                    prefix = f"{cur_svc}." if cur_svc else ""
                    rpcs.append(f"  - L{idx} `{prefix}{mr.group(1)}({mr.group(2).strip()}) -> {mr.group(3).strip()}`")
                    continue
                mm = msg_re.match(ln.strip())
                if mm:
                    msgs.append(mm.group(1))
            out.append(f"\n### `{rel(p)}`")
            out.extend(rpcs)
            if msgs:
                out.append(f"  - Messages ({len(msgs)}): " + ", ".join(f"`{m}`" for m in msgs[:40]))
        out.append("")

    sql_files = walk_source_files(cfg, (".sql",))
    if sql_files:
        out.append("## SQL Tables, Views & Typed Queries")
        ddl_re = re.compile(
            r"CREATE\s+(?:OR\s+REPLACE\s+)?(TABLE|VIEW)\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z0-9_.\"']+)",
            re.IGNORECASE,
        )
        sqlc_re = re.compile(r"^--\s*name:\s*([A-Za-z0-9_]+)\s*(:[a-z]+)")
        for p in sql_files:
            txt = p.read_text(encoding="utf-8", errors="replace")
            up_txt = txt.split("-- +goose Down")[0]
            ddls = [f"`{m.group(1).upper()} {m.group(2)}`" for m in ddl_re.finditer(up_txt)]
            queries = [
                f"`{m.group(1)}` ({m.group(2)})"
                for ln in txt.splitlines()
                for m in [sqlc_re.match(ln.strip())]
                if m
            ]
            if ddls or queries:
                out.append(f"- `{rel(p)}`: " + ", ".join(ddls + queries))
        out.append("")

    schema_files = walk_source_files(cfg, (".prisma", ".graphql", ".gql"))
    if schema_files:
        out.append("## Prisma / GraphQL Models & Operations")
        model_re = re.compile(r"^(model|enum|type|input|interface)\s+([A-Za-z0-9_]+)")
        for p in schema_files:
            defs = []
            for idx, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                m = model_re.match(ln.strip())
                if m:
                    defs.append(f"`{m.group(1)} {m.group(2)}` (L{idx})")
            if defs:
                out.append(f"- `{rel(p)}`: " + ", ".join(defs))
        out.append("")

    if len(out) <= 5:
        out.append("_(No SQL, Protobuf, Prisma, or GraphQL contracts detected yet.)_\n")

    return "\n".join(out).rstrip() + "\n"


def build_ui_and_i18n(cfg: Dict[str, Any]) -> str:
    out: List[str] = [
        "# UI Design Tokens & Localization Summary",
        "",
        "> Auto-generated by `scripts/pak/build_atlas.py`.",
        "",
    ]

    css_files = walk_source_files(cfg, (".css",))
    if css_files:
        out.append("## CSS Custom Properties & Themes")
        theme_re = re.compile(r'\[data-theme="([^"]+)"\]')
        var_re = re.compile(r"(--[a-zA-Z0-9_-]+)\s*:")
        for p in css_files:
            txt = p.read_text(encoding="utf-8", errors="replace")
            themes = sorted(set(theme_re.findall(txt)))
            css_vars = sorted(set(var_re.findall(txt)))
            if themes or css_vars:
                out.append(f"### `{rel(p)}`")
                if themes:
                    out.append("- Themes: " + ", ".join(f"`{t}`" for t in themes))
                if css_vars:
                    sample = ", ".join(f"`{v}`" for v in css_vars[:35])
                    more = f" (+{len(css_vars) - 35} more)" if len(css_vars) > 35 else ""
                    out.append(f"- CSS Tokens ({len(css_vars)}): {sample}{more}")
        out.append("")

    i18n_dir_rel = cfg.get("checks", {}).get("i18n_locales_dir", "")
    if i18n_dir_rel:
        locales_dir = ROOT / i18n_dir_rel
        base_file = locales_dir / cfg.get("checks", {}).get("i18n_base_locale", "en.json")
        if locales_dir.exists() and base_file.exists():
            locale_codes = sorted(p.stem for p in locales_dir.glob("*.json"))
            base_data = json.loads(base_file.read_text(encoding="utf-8"))
            out.append("## Localization (`i18n`)")
            out.append(f"- Directory: `{i18n_dir_rel}` ({len(locale_codes)} locales)")
            out.append(f"- Keys in `{base_file.name}`: `{len(base_data)}`")
            out.append("- Locales: " + ", ".join(f"`{c}`" for c in locale_codes))
            out.append("")

    if len(out) <= 5:
        out.append("_(No CSS token sheets or i18n locale catalogs configured.)_\n")

    return "\n".join(out).rstrip() + "\n"


def build_dependency_graph(cfg: Dict[str, Any]) -> str:
    out: List[str] = [
        "# Live Module Dependency & Reverse-Dependent Graph",
        "",
        "> Auto-generated by `scripts/pak/build_atlas.py`.",
        "> Check **Reverse Dependents** (`<-`) before modifying any shared package, module, or component.",
        "",
    ]

    # 1. Go Internal Package Graph
    gomod = ROOT / "go.mod"
    go_files = [p for p in walk_source_files(cfg, (".go",)) if not p.name.endswith("_test.go")]
    if gomod.exists() and go_files:
        mod_name = ""
        for ln in gomod.read_text(encoding="utf-8").splitlines():
            if ln.startswith("module "):
                mod_name = ln.split()[1].strip()
                break
        if mod_name:
            prefix = mod_name + "/"
            go_deps: Dict[str, Set[str]] = defaultdict(set)
            go_rev: Dict[str, Set[str]] = defaultdict(set)
            imp_re = re.compile(r'"([^"]+)"')
            for p in go_files:
                pkg = p.parent.relative_to(ROOT).as_posix()
                for m in imp_re.finditer(p.read_text(encoding="utf-8", errors="replace")):
                    imp = m.group(1)
                    if imp.startswith(prefix):
                        dep = imp[len(prefix):]
                        if dep != pkg and not is_skipped(dep, cfg):
                            go_deps[pkg].add(dep)
                            go_rev[dep].add(pkg)
            if go_rev:
                out.append("## Go Internal Package Dependencies")
                out.append("### Reverse Dependents (`Target <- Importers`)")
                for pkg in sorted(go_rev):
                    out.append(f"- `{pkg}` <- " + ", ".join(f"`{c}`" for c in sorted(go_rev[pkg])))
                out.append("\n### Outbound Imports (`Package -> Dependencies`)")
                for pkg in sorted(go_deps):
                    out.append(f"- `{pkg}` -> " + ", ".join(f"`{d}`" for d in sorted(go_deps[pkg])))
                out.append("")

    # 2. TypeScript / JavaScript Internal Module Graph
    ts_files = [
        p for p in walk_source_files(cfg, (".ts", ".tsx", ".js", ".jsx", ".mjs"))
        if not any(seg in p.name for seg in (".test.", ".spec.", ".stories."))
        and "/locales/" not in rel(p)
    ]
    if ts_files:
        ts_rev: Dict[str, Set[str]] = defaultdict(set)
        ts_imp_re = re.compile(r"""(?:from|import)\s*\(?['"](\.[^'"]+)['"]\)?""")

        def resolve_ts(src_file: Path, spec: str) -> str:
            base = (src_file.parent / spec).resolve()
            for ext in ("", ".ts", ".tsx", ".js", ".jsx", "/index.ts", "/index.tsx", "/index.js"):
                cand = Path(str(base) + ext)
                if cand.exists() and cand.is_file():
                    try:
                        return cand.relative_to(ROOT).as_posix()
                    except ValueError:
                        return ""
            return ""

        for p in ts_files:
            src_r = rel(p)
            for m in ts_imp_re.finditer(p.read_text(encoding="utf-8", errors="replace")):
                resolved = resolve_ts(p, m.group(1))
                if resolved and resolved != src_r and not is_skipped(resolved, cfg) and "/locales/" not in resolved:
                    ts_rev[resolved].add(src_r)

        if ts_rev:
            out.append("## TypeScript / JavaScript Reverse Dependents (`Module <- Importers`)")
            for target in sorted(ts_rev):
                out.append(f"- `{target}` <- " + ", ".join(f"`{c}`" for c in sorted(ts_rev[target])))
            out.append("")

    # 3. Python Internal Module Graph
    py_files = [
        p for p in walk_source_files(cfg, (".py",))
        if not p.name.startswith("test_") and not p.name.endswith("_test.py") and p.name != "__init__.py"
    ]
    if py_files:
        by_stem = {p.stem: rel(p) for p in py_files}
        py_rev: Dict[str, Set[str]] = defaultdict(set)
        py_imp_re = re.compile(r"^\s*(?:from\s+\.?([a-zA-Z0-9_]+)\s+import|import\s+([a-zA-Z0-9_]+))")
        for p in py_files:
            src_r = rel(p)
            for ln in p.read_text(encoding="utf-8", errors="replace").splitlines():
                m = py_imp_re.match(ln)
                if m:
                    mod = (m.group(1) or m.group(2)).split(".")[0]
                    if mod in by_stem and by_stem[mod] != src_r:
                        py_rev[by_stem[mod]].add(src_r)
        if py_rev:
            out.append("## Python Internal Reverse Dependents (`Module <- Importers`)")
            for target in sorted(py_rev):
                out.append(f"- `{target}` <- " + ", ".join(f"`{c}`" for c in sorted(py_rev[target])))
            out.append("")

    # 4. Rust Internal Module Graph (`use crate::...`)
    rs_files = walk_source_files(cfg, (".rs",))
    if rs_files:
        rs_rev: Dict[str, Set[str]] = defaultdict(set)
        rs_use_re = re.compile(r"^\s*use\s+crate::([a-zA-Z0-9_]+)")
        for p in rs_files:
            src_r = rel(p)
            for ln in p.read_text(encoding="utf-8", errors="replace").splitlines():
                m = rs_use_re.match(ln)
                if m:
                    rs_rev[f"crate::{m.group(1)}"].add(src_r)
        if rs_rev:
            out.append("## Rust Crate Module Reverse Dependents (`crate::mod <- Importers`)")
            for target in sorted(rs_rev):
                out.append(f"- `{target}` <- " + ", ".join(f"`{c}`" for c in sorted(rs_rev[target])))
            out.append("")

    if len(out) <= 6:
        out.append("_(No internal cross-module imports detected yet.)_\n")

    return "\n".join(out).rstrip() + "\n"


def discover_domain_dossiers() -> List[Tuple[str, str, str]]:
    entries: List[Tuple[str, str, str]] = []
    if not DOMAINS_DIR.exists():
        return entries
    paths_re = re.compile(r"^>\s*\*\*Paths:\*\*\s*`?([^`\n]+)`?", re.IGNORECASE)
    summary_re = re.compile(r"^>\s*\*\*Summary:\*\*\s*(.+)$", re.IGNORECASE)
    title_re = re.compile(r"^#\s+(.+)$")
    for p in sorted(DOMAINS_DIR.glob("*.md")):
        title = p.stem
        paths_pat = ""
        summary = ""
        for ln in p.read_text(encoding="utf-8", errors="replace").splitlines()[:15]:
            s = ln.strip()
            mt = title_re.match(s)
            if mt and title == p.stem:
                title = mt.group(1).replace("Domain Dossier:", "").strip()
            mp = paths_re.match(s)
            if mp:
                paths_pat = mp.group(1).strip()
            ms = summary_re.match(s)
            if ms:
                summary = ms.group(1).strip()
        entries.append((rel(p), paths_pat, summary or title))
    return entries


def build_system_map(cfg: Dict[str, Any]) -> str:
    proj = cfg.get("project_name", ROOT.name)
    quarantined = cfg.get("quarantined_paths", [])
    dossiers = discover_domain_dossiers()

    out = [
        f"# {proj} — System Map & Self-Evolving Context Index",
        "",
        "> Auto-generated by `scripts/pak/build_atlas.py`.",
        "> Consult `docs/atlas/*` before creating new functions and `docs/domains/*` before editing business logic.",
        "",
        "## 1. Atlas Index Files",
        "- `docs/atlas/01_CODE_CAPABILITIES.md` — Exported functions, classes, interfaces, hooks, and components.",
        "- `docs/atlas/02_DATA_CONTRACTS.md` — Database tables, migrations, typed SQL queries, Protobuf/GraphQL contracts.",
        "- `docs/atlas/03_UI_AND_ASSETS.md` — CSS design tokens, themes, and i18n locale summary.",
        "- `docs/atlas/04_DEPENDENCY_GRAPH.md` — Auto-extracted module dependencies & reverse dependents (`<-`).",
        "",
        "## 2. Quarantined Dead / Legacy Paths (DO NOT READ AS TRUTH OR EDIT)",
    ]
    if quarantined:
        for q in quarantined:
            out.append(f"- `{q}`")
    else:
        out.append("- _(None configured — add obsolete prototype folders to `quarantined_paths` in `pak.config.json`.)_")

    out.append("\n## 3. Dynamic Domain Dossier Routing Table (`docs/domains/`)")
    out.append("_(Auto-discovered from `docs/domains/*.md` — add `> **Paths:**` & `> **Summary:**` headers to register new domains automatically)_")
    if dossiers:
        for d_path, pat, summary in dossiers:
            suffix = f" *(matches: `{pat}`)*" if pat else ""
            out.append(f"- `{d_path}` — {summary}{suffix}")
    else:
        out.append("- _(Run the `pak-bootstrap` skill to audit the codebase and generate domain dossiers.)_")

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Build pak zero-token Codebase Atlas & Dependency Graph")
    parser.add_argument("--quiet", action="store_true", help="Suppress summary output")
    args = parser.parse_args()

    cfg = load_config()
    ATLAS_DIR.mkdir(parents=True, exist_ok=True)

    files = {
        "00_SYSTEM_MAP.md": build_system_map(cfg),
        "01_CODE_CAPABILITIES.md": build_code_capabilities(cfg),
        "02_DATA_CONTRACTS.md": build_data_contracts(cfg),
        "03_UI_AND_ASSETS.md": build_ui_and_i18n(cfg),
        "04_DEPENDENCY_GRAPH.md": build_dependency_graph(cfg),
    }

    for name, content in files.items():
        target = ATLAS_DIR / name
        old = target.read_text(encoding="utf-8") if target.exists() else None
        if old != content:
            target.write_text(content, encoding="utf-8")

    if not args.quiet:
        print(f"[pak] Generated {len(files)} Atlas & Dependency Graph indexes in docs/atlas/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
